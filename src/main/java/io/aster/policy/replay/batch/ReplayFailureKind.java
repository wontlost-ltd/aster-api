package io.aster.policy.replay.batch;

/**
 * 批次重跑的失败分类（ADR 0034 §4.2）。
 *
 * <p><b>为什么要分类而不是只记一句「失败了」</b>：批次是 fail-closed 的——
 * 一条失败就整批拒答。用户面对的是「没有数字」，此时唯一有用的信息是
 * <b>为什么</b>：是自己的数据有问题（可以清理后重跑），还是版本本身不兼容
 * （重跑多少次都没用）。只说「失败」会让用户反复重试同一件注定失败的事。
 *
 * <p>分类是**面向用户决策**的，不是面向异常类型的——
 * 同一个 Java 异常可能落在不同分类里，取决于它意味着用户该做什么。
 */
public enum ReplayFailureKind {

    /**
     * 目标版本的源码编译失败。
     *
     * <p>用户可做的：检查目标版本本身是否可用。重跑无用。
     */
    TARGET_COMPILE_ERROR,

    /**
     * 历史输入在目标版本上求值失败（类型不匹配、缺字段等）。
     *
     * <p>这是最常见的一类，也是**选择偏差的源头**——
     * 它与输入内容强相关，故绝不能「跳过失败的、只算成功的」。
     */
    INPUT_INCOMPATIBLE,

    /**
     * 词汇/别名快照缺失或加载失败。
     *
     * <p>用户可做的：检查该执行关联的词汇集是否仍存在。
     */
    VOCABULARY_UNAVAILABLE,

    /**
     * 执行超时。
     *
     * <p>用户可做的：稍后重试，或缩小窗口。
     */
    TIMEOUT,

    /**
     * 并发闸门拒绝（服务端繁忙）。
     *
     * <p>用户可做的：稍后重试。★这**不是**用户数据的问题，
     * 文案上要与 INPUT_INCOMPATIBLE 明确区分，否则用户会去改自己没错的数据。
     */
    THROTTLED,

    /**
     * 其余未归类错误。
     *
     * <p>★这一类占比高本身就是信号：说明分类不够细，该补而不是放着。
     */
    UNKNOWN;

    /** 是否属于「重跑可能成功」——决定 UI 是否提示重试。 */
    public boolean isRetryable() {
        return this == TIMEOUT || this == THROTTLED;
    }
}
